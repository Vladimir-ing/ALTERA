  function submit(text) {
    state.complaint = text;

    var html = '<p>' + escape(text) + '</p>';
    if (state.photo) {
      html += '<figure class="shot"><img src="' + state.photo.src + '" alt="Приложенная фотография">' +
        '<figcaption>' + escape(state.photo.name) + '</figcaption></figure>';
    }
    say('you', html);

    var flag = findRedFlag(text);
    if (flag) {
      alarm(flag);
      return;
    }

    state.direction = route(text);
    triage(0);
  }

