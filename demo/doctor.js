  // Реплики идут по очереди с паузой — иначе диалог сваливается одним куском.
  function sequence(steps, done) {
    panel.innerHTML = '';
    var index = 0;

    function next() {
      if (index >= steps.length) {
        if (done) { done(); }
        return;
      }
      steps[index++]();
      thread.scrollTop = thread.scrollHeight;
      window.setTimeout(next, PAUSE);
    }

    next();
  }

