  /* ── Уточнения терапевта ─────────────────────────────────────────────── */

  function triage(index) {
    if (index >= TRIAGE.length) {
      handoff();
      return;
    }

    var question = TRIAGE[index];
    sequence([
      function () { say('therapist', '<p>' + question.label + '</p>'); }
    ], function () {
      choices(question, function (option) {
        state.answers[question.key] = option.id;
        say('you', '<p>' + option.label + '</p>');
        triage(index + 1);
      });
    });
  }

  function choices(question, onPick) {
    panel.innerHTML = '<div class="ask"><p class="ask-label">' + question.label + '</p><div class="options"></div></div>';
    var box = panel.querySelector('.options');

    question.options.forEach(function (option) {
      var button = document.createElement('button');
      button.type = 'button';
      button.className = 'option';
      button.textContent = option.label;
      button.addEventListener('click', function () {
        panel.innerHTML = '';
        onPick(option);
      });
      box.appendChild(button);
    });
  }

