  function normalize(text) {
    return String(text).toLowerCase().replace(/ё/g, 'е');
  }

  function hasAny(text, list) {
    if (!list) { return false; }
    for (var i = 0; i < list.length; i++) {
      if (text.indexOf(normalize(list[i])) !== -1) { return true; }
    }
    return false;
  }

  function findRedFlag(text) {
    var hay = normalize(text);
    for (var i = 0; i < RED_FLAGS.length; i++) {
      var flag = RED_FLAGS[i];
      if (!hasAny(hay, flag.any)) { continue; }
      if (flag.with && !hasAny(hay, flag.with)) { continue; }
      if (flag.unless && hasAny(hay, flag.unless)) { continue; }
      return flag;
    }
    return null;
  }

  function route(text) {
    var hay = normalize(text);
    var best = null;
    var bestScore = 0;

    Object.keys(DIRECTIONS).forEach(function (id) {
      var score = 0;
      DIRECTIONS[id].words.forEach(function (word) {
        if (hay.indexOf(normalize(word)) !== -1) { score++; }
      });
      if (score > bestScore) { bestScore = score; best = id; }
    });

    return { id: best || 'therapist', matched: bestScore > 0 };
  }

  // Совпадение по ключу: обычные ключи смотрят в ответы, особые — в контекст.
  function matches(key, values, state) {
    if (key === 'long') {
      return state.answers.duration === 'weeks' || state.answers.duration === 'months';
    }
    if (key === 'fever') {
      return state.answers.temperature && state.answers.temperature !== 'none';
    }
    if (key === 'photo') { return !!state.photo; }
    return values.indexOf(state.answers[key]) !== -1;
  }

  function versions(state) {
    var scored = [];

    DERM_VERSIONS.forEach(function (version) {
      var need = version.need || {};
      var keys = Object.keys(need);
      for (var i = 0; i < keys.length; i++) {
        if (!matches(keys[i], need[keys[i]], state)) { return; }
      }

      var score = version.weight;
      var bonus = version.bonus || {};
      Object.keys(bonus).forEach(function (key) {
        if (matches(key, bonus[key], state)) { score += 1; }
      });

      scored.push({ version: version, score: score });
    });

    scored.sort(function (a, b) { return b.score - a.score; });

    var top = scored.filter(function (item) { return item.version.id !== 'unclear'; }).slice(0, 3);
    if (!top.length) {
      top = scored.slice(0, 1);
    }
    return top.map(function (item) { return item.version; });
  }

  function urgency(state) {
    if (state.answers.temperature === 'high') { return 'сегодня'; }
    if (state.answers.duration === 'months') { return 'плановая запись'; }
    return 'на этой неделе';
  }

  function labelOf(key, id) {
    var flows = TRIAGE.concat(DERM_FLOW);
    for (var i = 0; i < flows.length; i++) {
      if (flows[i].key !== key) { continue; }
      var options = flows[i].options;
      for (var j = 0; j < options.length; j++) {
        if (options[j].id === id) { return options[j].label; }
      }
    }
    return id;
  }

